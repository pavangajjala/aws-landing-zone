#!/usr/bin/env python3
"""Generate Terraform backend configs from environments.yaml.

    python scripts/gen_backend.py            # write every environment
    python scripts/gen_backend.py dev        # write one
    python scripts/gen_backend.py --check    # fail if any file is missing or stale (for CI)

Each environment gets `<root>/backend/<name>.hcl`, used as:

    terraform -chdir=live/workload init -backend-config=backend/dev.hcl
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
NAME_PATTERN = re.compile(r"^[a-z][a-z0-9-]{1,30}$")
REQUIRED_STATE_KEYS = ("bucket", "region", "lock_table")


class ConfigError(ValueError):
    pass


def load_config(path: Path) -> dict:
    config = yaml.safe_load(path.read_text()) or {}
    state = config.get("state") or {}
    missing = [key for key in REQUIRED_STATE_KEYS if not state.get(key)]
    if missing:
        raise ConfigError(f"state is missing: {', '.join(missing)}")
    environments = config.get("environments") or {}
    if not environments:
        raise ConfigError("no environments defined")
    for name, env in environments.items():
        if not NAME_PATTERN.match(str(name)):
            raise ConfigError(f"invalid environment name: {name!r}")
        if not (env or {}).get("root"):
            raise ConfigError(f"environment {name!r} has no root")
    return config


def render(name: str, state: dict) -> str:
    """Render one backend file. The state key is derived from the name so two
    environments can never point at the same state object."""
    lines = [
        "# Generated by scripts/gen_backend.py from environments.yaml. Do not edit.",
        f'bucket         = "{state["bucket"]}"',
        f'key            = "{name}/terraform.tfstate"',
        f'region         = "{state["region"]}"',
        f'dynamodb_table = "{state["lock_table"]}"',
        "encrypt        = true",
    ]
    if state.get("kms_alias"):
        lines.append(f'kms_key_id     = "{state["kms_alias"]}"')
    return "\n".join(lines) + "\n"


def target_path(repo_root: Path, name: str, env: dict) -> Path:
    return repo_root / env["root"] / "backend" / f"{name}.hcl"


def generate(config: dict, repo_root: Path, only: str | None = None, check: bool = False) -> list[str]:
    """Write (or, with check=True, verify) backend files. Returns the stale ones."""
    environments = config["environments"]
    if only and only not in environments:
        raise ConfigError(f"unknown environment: {only!r} (known: {', '.join(sorted(environments))})")
    stale = []
    for name, env in environments.items():
        if only and name != only:
            continue
        path = target_path(repo_root, name, env)
        content = render(name, config["state"])
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(repo_root)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(repo_root)}")
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("environment", nargs="?", help="only generate this environment")
    parser.add_argument("--config", default=str(REPO_ROOT / "environments.yaml"))
    parser.add_argument("--check", action="store_true", help="verify files instead of writing them")
    args = parser.parse_args(argv)
    try:
        config = load_config(Path(args.config))
        stale = generate(config, REPO_ROOT, args.environment, args.check)
    except (ConfigError, OSError, yaml.YAMLError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if stale:
        print("stale or missing backend files:\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
